from datetime import datetime, timezone
from enum import Enum
from typing import Literal

from pydantic import BaseModel, Field, ConfigDict


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class MoodType(str, Enum):
    NEUTRAL = "neutral"
    HAPPY = "happy"
    CURIOUS = "curious"
    EXCITED = "excited"
    THOUGHTFUL = "thoughtful"
    CONFUSED = "confused"
    SAD = "sad"
    MISCHIEVOUS = "mischievous"
    BORED = "bored"


class MoodState(BaseModel):
    """The robot's current emotional disposition."""

    mood: MoodType = MoodType.NEUTRAL

    valence: float = Field(
        default=0.2,
        ge=-1.0,
        le=1.0,
        description="Negative to positive emotional tone.",
    )

    arousal: float = Field(
        default=0.4,
        ge=0.0,
        le=1.0,
        description="Calm to highly stimulated.",
    )

    energy: float = Field(
        default=0.7,
        ge=0.0,
        le=1.0,
        description="Current energy and activity level.",
    )

    curiosity: float = Field(
        default=0.6,
        ge=0.0,
        le=1.0,
        description="Current drive to investigate something.",
    )

    sociability: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Current willingness to interact.",
    )


class AttentionState(BaseModel):
    """What the robot is currently focused on."""

    topic: str | None = None

    source: Literal[
        "user",
        "environment",
        "internal",
    ] | None = None

    intensity: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
    )

    since: datetime = Field(default_factory=utc_now)

    current_thought: str | None = Field(
        default=None,
        description=(
            "A short, explicit summary of the robot's current "
            "preoccupation, not hidden model reasoning."
        ),
    )


class Interest(BaseModel):
    """An ongoing subject of curiosity."""

    topic: str

    strength: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
    )

    reason: str = Field(
        default="",
        description="Why this topic interests the robot.",
    )

    last_engaged: datetime = Field(default_factory=utc_now)

    times_engaged: int = Field(default=0, ge=0)


class MotivationStatus(str, Enum):
    ACTIVE = "active"
    PAUSED = "paused"
    COMPLETED = "completed"
    ABANDONED = "abandoned"


class Motivation(BaseModel):
    """Something the robot would like to pursue."""

    id: str = Field(
        description="Stable identifier for this motivation."
    )

    description: str

    priority: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
    )

    status: MotivationStatus = MotivationStatus.ACTIVE

    origin: str = Field(
        default="reflection",
        description="How the motivation arose.",
    )

    created_at: datetime = Field(default_factory=utc_now)

    last_considered: datetime | None = None


class RobotState(BaseModel):
    """
    The robot's current internal state.

    This is owned by the Python application and persists
    between LLM calls.
    """

    model_config = ConfigDict(
        validate_assignment=True,
        extra="forbid",
    )

    version: int = Field(default=0, ge=0)

    updated_at: datetime = Field(default_factory=utc_now)

    mood: MoodState = Field(default_factory=MoodState)

    attention: AttentionState = Field(
        default_factory=AttentionState
    )

    interests: list[Interest] = Field(default_factory=list)

    motivations: list[Motivation] = Field(default_factory=list)

    desire_to_speak: float = Field(
        default=0.2,
        ge=0.0,
        le=1.0,
        description=(
            "Internal inclination to initiate conversation. "
            "Not permission to speak automatically."
        ),
    )

    last_user_interaction: datetime | None = None

    last_spontaneous_interaction: datetime | None = None


class StateUpdate(BaseModel):
    """
    Proposed changes to the robot's state.

    Generated by a reflection model and validated before
    being applied by the Python state manager.
    """

    model_config = ConfigDict(extra="forbid")

    reason: str = Field(
        description="Brief explanation of the proposed changes."
    )

    mood: MoodState | None = None

    attention: AttentionState | None = None

    new_interests: list[Interest] = Field(default_factory=list)

    interest_updates: list[Interest] = Field(default_factory=list)

    new_motivations: list[Motivation] = Field(
        default_factory=list
    )

    motivation_updates: list[Motivation] = Field(
        default_factory=list
    )

    desire_to_speak: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    based_on_version: int = Field(
        ge=0,
        description="State version used to produce this update."
    )